"""Importing a bench export into runs.

Test benches write a file at the end of a session and it is the only way a shop
of any size gets its results onto the book. The file is generated, so it is
consistent, and it is generated by a program written by the bench manufacturer,
so it is consistent with itself rather than with anything here.

The import is deliberately forgiving in one direction and unforgiving in the
other. A row naming a meter nobody has is skipped with a reason, because a bench
operator typing a serial wrong should not stop the other forty rows landing. A
row that would produce a run the model refuses is also skipped with its reason.
But a file missing a required column is refused outright, because that is not a
row problem, it is the wrong file.

Nothing is judged here. The runs go on the book as measurements and the verdict
comes later, which matters when a standard's certificate turns out to have
lapsed: the measurements are still real, they are just not usable.
"""

from __future__ import annotations

from pathlib import Path

from kilodial.errors import ShopError
from kilodial.ingest.sheet import Outcome, Row, Sheet, read_file, read_text
from kilodial.model.run import BenchRun, RunKind
from kilodial.store.shop import Shop
from kilodial.testing.record import Readings, build_run

REQUIRED = ["reference", "meter", "bench", "kind", "tested", "technician"]
KINDS = {k.value.replace(" ", "_"): k for k in RunKind}

CREEP = {"held": False, "crept": True, "no": False, "yes": True, "": None}


def run_kind(text: str) -> RunKind:
    """Read a run kind out of whatever the bench wrote."""
    key = text.strip().lower().replace("-", "_").replace(" ", "_")
    if key not in KINDS:
        raise ShopError(f"{text!r} is not a run kind")
    return KINDS[key]


def creep_of(row: Row) -> bool | None:
    """Read the creep column, treating a blank as no creep test done."""
    written = (row.get("creep") or "").strip().lower()
    if written not in CREEP:
        raise ShopError(f"creep is held or crept, not {written!r}")
    return CREEP[written]


def run_from(shop: Shop, row: Row) -> BenchRun:
    """Build one run out of one row, resolving what it names off the book."""
    serial = shop.meters.get(row.need("meter")).serial
    bench = shop.benches.get(row.need("bench"))
    named = row.get("standard")
    standard = shop.standards.get(named if named else bench.standard_serial)
    return build_run(
        row.need("reference"),
        device=shop.device_for(serial),
        meter_serial=serial,
        bench_code=bench.code,
        standard_serial=standard.serial,
        kind=run_kind(row.need("kind")),
        tested_on=row.need("tested"),
        technician=row.need("technician"),
        readings=Readings.of(
            full_load=row.get("fl"),
            light_load=row.get("ll"),
            power_factor=row.get("pf"),
            heavy_load=row.get("hl"),
            register=row.get("register"),
            demand=row.get("demand"),
            crept=creep_of(row),
        ),
        note=row.get("note"),
        volts=row.get("volts"),
    )


def load(shop: Shop, sheet: Sheet) -> Outcome:
    """Put every row that can be a run onto the book, skipping the rest."""
    taken = 0
    skipped: list[tuple[int, str]] = []
    for row in sheet:
        try:
            run = run_from(shop, row)
        except ShopError as exc:
            skipped.append((row.line, str(exc)))
            continue
        if shop.runs.exists(run.reference):
            skipped.append((row.line, f"run {run.reference} is already on the book"))
            continue
        try:
            shop.runs.add(run)
        except ShopError as exc:
            skipped.append((row.line, str(exc)))
            continue
        taken += 1
    return Outcome(taken, tuple(skipped))


def load_text(shop: Shop, text: str) -> Outcome:
    """Import a bench export held in a string."""
    return load(shop, read_text(text, required=REQUIRED))


def load_file(shop: Shop, path: str | Path) -> Outcome:
    """Import a bench export off disk."""
    return load(shop, read_file(path, required=REQUIRED))


__all__ = [
    "CREEP",
    "KINDS",
    "REQUIRED",
    "creep_of",
    "load",
    "load_file",
    "load_text",
    "run_from",
    "run_kind",
]
