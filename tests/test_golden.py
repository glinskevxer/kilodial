"""Render every report against one fixed book and compare it to a stored copy.

The report tests elsewhere check that a figure is right. This checks that the
whole page is what it was, which catches the changes those tests are blind to: a
column that vanished, a heading that changed, a section that stopped being
printed because a fact became empty.

The stored copies are regenerated by running this file with ``--golden``, which
is deliberately awkward. A golden file that is easy to update is one that gets
updated instead of read, and the whole value here is that somebody looks at the
diff and decides whether it is an improvement or a regression.

The book is fixed and so is every date, so a run of this test at any time of any
year produces the same bytes.
"""

from __future__ import annotations

import os
from collections.abc import Iterator
from pathlib import Path

import pytest

from kilodial.adjust.compute import BilledMonth
from kilodial.model.repair import Fault, Repair
from kilodial.model.run import RunKind
from kilodial.model.technician import Grade, Technician
from kilodial.report import bench, certifications, commission, faults, register
from kilodial.report import shop as shop_report
from kilodial.report.document import Document
from kilodial.store.shop import Shop, open_shop
from kilodial.testing.record import Readings, build_run
from kilodial.tools.smoke import stand_up
from kilodial.xfmr.transformer import InstrumentTransformer, TransformerKind

GOLDEN = Path(__file__).parent / "golden"
AS_AT = "2025-07-15"
FIRST = "2025-01-01"
LAST = "2025-12-31"
LAST_DAY = {
    1: 31,
    2: 28,
    3: 31,
    4: 30,
    5: 31,
    6: 30,
    7: 31,
    8: 31,
    9: 30,
    10: 31,
    11: 30,
    12: 31,
}


@pytest.fixture
def shop(tmp_path: Path) -> Iterator[Shop]:
    opened = open_shop(tmp_path / "golden.sqlite3", create=True)
    stand_up(opened)
    opened.technicians.add(
        Technician.build(
            "T-441",
            "R Ellis",
            grade=Grade.SUPERVISOR,
            certified_on="2020-01-01",
            certificate_due="2030-01-01",
        )
    )
    opened.transformers.add(
        InstrumentTransformer.build(
            "CT-8841",
            kind=TransformerKind.CURRENT,
            maker="Ferrand",
            marked_ratio="40",
            accuracy="0.3",
            rcf="1.0020",
            phase_minutes="12",
            tested_on="2022-05-01",
        )
    )
    opened.runs.add(
        build_run(
            "TR-1",
            device=opened.device_for("84-119302"),
            meter_serial="84-119302",
            bench_code="B2",
            standard_serial="RS-5511",
            kind=RunKind.AS_FOUND,
            tested_on="2025-06-30",
            technician="R Ellis",
            badge="T-441",
            readings=Readings.of(full_load="103.20", light_load="102.40"),
        )
    )
    opened.repairs.add(
        Repair.build(
            "RP-1",
            "84-119302",
            Fault.BEARING,
            repaired_on="2025-07-02",
            by="R Ellis",
            hours="1",
            parts="12.40",
            replacement_cost="184.00",
        )
    )
    for month in range(7, 13):
        opened.billing.add(
            "SP-1042",
            BilledMonth.of(f"2025-{month:02d}-01", f"2025-{month:02d}-{LAST_DAY[month]}", "100.00"),
        )
    yield opened
    opened.close()


def reports(shop: Shop) -> dict[str, Document]:
    """Every report, built against the fixed book on the fixed dates."""
    return {
        "shop": shop_report.build(shop, on=AS_AT),
        "register": register.build(shop, on=AS_AT),
        "certificates": certifications.build(shop, on=AS_AT),
        "commission": commission.build(shop, first=FIRST, last=LAST),
        "faults": faults.build(shop, first=FIRST, last=LAST),
        "bench": bench.build(shop, first=FIRST, last=LAST),
    }


def golden_path(name: str, shape: str) -> Path:
    return GOLDEN / f"{name}.{shape}"


def rendered(doc: Document, shape: str) -> str:
    return doc.as_json() if shape == "json" else doc.render()


@pytest.mark.parametrize(
    "name", ["shop", "register", "certificates", "commission", "faults", "bench"]
)
@pytest.mark.parametrize("shape", ["txt", "json"])
def test_a_report_renders_the_way_it_did(shop: Shop, name: str, shape: str) -> None:
    doc = reports(shop)[name]
    text = rendered(doc, shape)
    path = golden_path(name, shape)
    if os.environ.get("KILODIAL_GOLDEN"):  # pragma: no cover - a deliberate rewrite
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    assert path.exists(), f"{path} is missing, rerun with KILODIAL_GOLDEN=1"
    assert text == path.read_text(), f"{name} as {shape} changed; look at the diff"


def test_every_report_has_a_stored_copy() -> None:
    for name in ("shop", "register", "certificates", "commission", "faults", "bench"):
        for shape in ("txt", "json"):
            assert golden_path(name, shape).exists()


def test_the_stored_copies_are_not_empty() -> None:
    for path in GOLDEN.iterdir():
        assert path.read_text().strip()


def test_the_book_is_the_same_every_run(shop: Shop) -> None:
    assert shop.summary()["runs"] == 1
    assert shop.summary()["repairs"] == 1
    assert shop.summary()["billed months"] == 12
